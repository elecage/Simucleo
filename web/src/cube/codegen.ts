/** newlib system calls, as CubeIDE's syscalls.c (written by Simucleo): printf → __io_putchar. */
export const SYSCALLS_C = `/**
 ******************************************************************************
 * @file      syscalls.c
 * @brief     Minimal System calls file (newlib), as STM32CubeIDE generates one.
 *            printf() ends in _write(), which hands every character to
 *            __io_putchar(): define it in main.c (USER CODE 0) to send it
 *            over a UART, e.g. USART2 to the ST-LINK virtual COM port.
 ******************************************************************************
 */
#include <errno.h>
#include <sys/stat.h>
#include <sys/time.h>
#include <sys/times.h>

extern int __io_putchar(int ch) __attribute__((weak));
extern int __io_getchar(void) __attribute__((weak));

int _getpid(void)
{
  return 1;
}

int _kill(int pid, int sig)
{
  (void)pid;
  (void)sig;
  errno = EINVAL;
  return -1;
}

void _exit(int status)
{
  _kill(status, -1);
  while (1) {}
}

int _read(int file, char *ptr, int len)
{
  (void)file;
  int n = 0;
  if (!__io_getchar) return 0;
  for (; n < len; n++)
  {
    *ptr++ = (char)__io_getchar();
  }
  return n;
}

int _write(int file, char *ptr, int len)
{
  (void)file;
  if (!__io_putchar) return len;
  for (int n = 0; n < len; n++)
  {
    __io_putchar(*ptr++);
  }
  return len;
}

int _close(int file)
{
  (void)file;
  return -1;
}

int _fstat(int file, struct stat *st)
{
  (void)file;
  st->st_mode = S_IFCHR;
  return 0;
}

int _isatty(int file)
{
  (void)file;
  return 1;
}

int _lseek(int file, int ptr, int dir)
{
  (void)file;
  (void)ptr;
  (void)dir;
  return 0;
}
`;

/** The heap for malloc (and printf's buffers), as CubeIDE's sysmem.c. */
export const SYSMEM_C = `/**
 ******************************************************************************
 * @file      sysmem.c
 * @brief     _sbrk() for newlib's malloc, as STM32CubeIDE generates one: the
 *            heap grows from the end of .bss (_end) up to the reserved stack
 *            (_estack - _Min_Stack_Size, from the linker script).
 ******************************************************************************
 */
#include <errno.h>
#include <stdint.h>
#include <stddef.h>

static uint8_t *__sbrk_heap_end = NULL;

void *_sbrk(ptrdiff_t incr)
{
  extern uint8_t _end;
  extern uint8_t _estack;
  extern uint32_t _Min_Stack_Size;
  const uint32_t stack_limit = (uint32_t)&_estack - (uint32_t)&_Min_Stack_Size;
  const uint8_t *max_heap = (uint8_t *)stack_limit;
  uint8_t *prev_heap_end;

  if (NULL == __sbrk_heap_end)
  {
    __sbrk_heap_end = &_end;
  }
  if (__sbrk_heap_end + incr > max_heap)
  {
    errno = ENOMEM;
    return (void *)-1;
  }
  prev_heap_end = __sbrk_heap_end;
  __sbrk_heap_end += incr;
  return (void *)prev_heap_end;
}
`;

