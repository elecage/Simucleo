const R = (name: string, body = "\n\n") => `/* USER CODE BEGIN ${name} */${body}/* USER CODE END ${name} */`;

function header(file: string, brief: string): string {
  return R(
    "Header",
    `
/**
  ******************************************************************************
  * @file           : ${file}
  * @brief          : ${brief}
  ******************************************************************************
  * @attention
  *
  * Generated by Simucleo's configuration tool (CubeMX layout) for the
  * STM32F401RETx on the NUCLEO-F401RE. Write your code inside the
  * USER CODE BEGIN/END regions: it is kept when the code is regenerated.
  *
  ******************************************************************************
  */
`,
  );
}

const PULL = { none: "GPIO_NOPULL", up: "GPIO_PULLUP", down: "GPIO_PULLDOWN" } as const;
const SPEED = { low: "GPIO_SPEED_FREQ_LOW", medium: "GPIO_SPEED_FREQ_MEDIUM", high: "GPIO_SPEED_FREQ_HIGH", very_high: "GPIO_SPEED_FREQ_VERY_HIGH" } as const;
const EDGE = { rising: "GPIO_MODE_IT_RISING", falling: "GPIO_MODE_IT_FALLING", both: "GPIO_MODE_IT_RISING_FALLING" } as const;

/** Configured pins in package order. */
function pinsInOrder(c: CubeConfig): [string, PinConfig][] {
  return PACKAGE_PINS.filter((p) => c.pins[p.name]).map((p) => [p.name, c.pins[p.name]]);
}

const pinMacro = (pin: string, v: PinConfig) => (v.label ? `${labelMacro(v.label)}_Pin` : `GPIO_PIN_${portPin(pin).pin}`);
const portOf = (pin: string) => `GPIO${portPin(pin).port}`;
/** The port of a group: the label's `_GPIO_Port` when the group is one labelled pin. */
const portExpr = (pins: [string, PinConfig][]) => (pins.length === 1 && pins[0][1].label ? `${labelMacro(pins[0][1].label)}_GPIO_Port` : portOf(pins[0][0]));
const pinList = (pins: [string, PinConfig][]) => pins.map(([p, v]) => pinMacro(p, v)).join("|");
const pinNames = (pins: [string, PinConfig][]) => pins.map(([p, v]) => (v.label ? `${labelMacro(v.label)}_Pin` : p)).join(" ");

/** Group pins (same port) by a key, keeping package order of first members. */
function group<T>(pins: [string, PinConfig][], key: (pin: string, v: PinConfig) => T): [string, PinConfig][][] {
  const out: { k: string; pins: [string, PinConfig][] }[] = [];
  for (const [p, v] of pins) {
    const k = `${portPin(p).port}|${JSON.stringify(key(p, v))}`;
    const g = out.find((x) => x.k === k);
    if (g) g.pins.push([p, v]);
    else out.push({ k, pins: [[p, v]] });
  }
  return out.map((g) => g.pins);
}

const isGpio = (s: string) => /^(GPIO_(Input|Output|Analog)|GPXTI\d+)$/.test(s);
const nvicOn = (c: CubeConfig, irq: string) => !!c.nvic[irq]?.enabled;
const nvicLines = (c: CubeConfig, irq: string, indent: string) =>
  `${indent}HAL_NVIC_SetPriority(${irq}_IRQn, ${c.nvic[irq].preempt}, ${c.nvic[irq].sub});\n${indent}HAL_NVIC_EnableIRQ(${irq}_IRQn);\n`;

const handleOf = (p: string) => {
  if (/^USART/.test(p)) return `huart${p.slice(5)}`;
  if (/^I2C/.test(p)) return `hi2c${p.slice(3)}`;
  if (/^SPI/.test(p)) return `hspi${p.slice(3)}`;
  if (/^TIM/.test(p)) return `htim${p.slice(3)}`;
  return `hadc${p.slice(3)}`;
};
const typeOf = (p: string) => (/^USART/.test(p) ? "UART_HandleTypeDef" : /^I2C/.test(p) ? "I2C_HandleTypeDef" : /^SPI/.test(p) ? "SPI_HandleTypeDef" : /^TIM/.test(p) ? "TIM_HandleTypeDef" : "ADC_HandleTypeDef");
const initName = (p: string) => (/^USART/.test(p) ? `MX_${p}_UART_Init` : `MX_${p}_Init`);
const pwmTimers = (c: CubeConfig) => TIMS.filter((t) => c.tim[t]?.channels.some(Boolean));

/** Handles in CubeMX's order (by type: ADC, I2C, SPI, TIM, UART). */
function handles(c: CubeConfig): string[] {
  const ps = peripherals(c);
  const order = ["ADC", "I2C", "SPI", "TIM", "USART"];
  return [...ps].sort((a, b) => order.findIndex((o) => a.startsWith(o)) - order.findIndex((o) => b.startsWith(o)) || a.localeCompare(b, "en", { numeric: true }));
}

// ------------------------------------------------------------------ main.h

export function mainH(c: CubeConfig): string {
  const defines: string[] = [];
  for (const [pin, v] of pinsInOrder(c)) {
    if (!v.label) continue;
    const m = labelMacro(v.label);
    defines.push(`#define ${m}_Pin GPIO_PIN_${portPin(pin).pin}`);
    defines.push(`#define ${m}_GPIO_Port ${portOf(pin)}`);
    if (/^GPXTI/.test(v.signal)) defines.push(`#define ${m}_EXTI_IRQn ${extiIrq(portPin(pin).pin)}_IRQn`);
  }
  return `${header("main.h", "Header for main.c file.\n  *                   This file contains the common defines of the application.")}

/* Define to prevent recursive inclusion -------------------------------------*/
#ifndef __MAIN_H
#define __MAIN_H

#ifdef __cplusplus
extern "C" {
#endif

/* Includes ------------------------------------------------------------------*/
#include "stm32f4xx_hal.h"

/* Private includes ----------------------------------------------------------*/
${R("Includes")}

/* Exported types ------------------------------------------------------------*/
${R("ET")}

/* Exported constants --------------------------------------------------------*/
${R("EC")}

/* Exported macro ------------------------------------------------------------*/
${R("EM")}
${pwmTimers(c).length ? "\nvoid HAL_TIM_MspPostInit(TIM_HandleTypeDef *htim);\n" : ""}
/* Exported functions prototypes ---------------------------------------------*/
void Error_Handler(void);

${R("EFP")}

/* Private defines -----------------------------------------------------------*/
${defines.length ? defines.join("\n") + "\n" : ""}
${R("Private defines")}

#ifdef __cplusplus
}
#endif

#endif /* __MAIN_H */
`;
}

