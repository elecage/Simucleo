function systemClock(c: CubeConfig): string {
  const k = c.clock;
  const t = computeClock(k);
  const hsiUsed = k.sysclk === "HSI" || (k.pllOn && k.pllSource === "HSI");
  const hseUsed = k.hse !== "off" && (k.sysclk === "HSE" || (k.pllOn && k.pllSource === "HSE"));
  const osc = [hseUsed && "RCC_OSCILLATORTYPE_HSE", hsiUsed && "RCC_OSCILLATORTYPE_HSI"].filter(Boolean).join("|") || "RCC_OSCILLATORTYPE_HSI";
  let s = `void SystemClock_Config(void)
{
  RCC_OscInitTypeDef RCC_OscInitStruct = {0};
  RCC_ClkInitTypeDef RCC_ClkInitStruct = {0};

  /** Configure the main internal regulator output voltage
  */
  __HAL_RCC_PWR_CLK_ENABLE();
  __HAL_PWR_VOLTAGESCALING_CONFIG(PWR_REGULATOR_VOLTAGE_SCALE${k.vos});

  /** Initializes the RCC Oscillators according to the specified parameters
  * in the RCC_OscInitTypeDef structure.
  */
  RCC_OscInitStruct.OscillatorType = ${osc};
`;
  if (hseUsed) s += `  RCC_OscInitStruct.HSEState = ${k.hse === "bypass" ? "RCC_HSE_BYPASS" : "RCC_HSE_ON"};\n`;
  if (hsiUsed || !hseUsed) s += `  RCC_OscInitStruct.HSIState = RCC_HSI_ON;\n  RCC_OscInitStruct.HSICalibrationValue = RCC_HSICALIBRATION_DEFAULT;\n`;
  if (k.pllOn) {
    s += `  RCC_OscInitStruct.PLL.PLLState = RCC_PLL_ON;
  RCC_OscInitStruct.PLL.PLLSource = RCC_PLLSOURCE_${k.pllSource};
  RCC_OscInitStruct.PLL.PLLM = ${k.pllM};
  RCC_OscInitStruct.PLL.PLLN = ${k.pllN};
  RCC_OscInitStruct.PLL.PLLP = RCC_PLLP_DIV${k.pllP};
  RCC_OscInitStruct.PLL.PLLQ = ${k.pllQ};
`;
  } else s += `  RCC_OscInitStruct.PLL.PLLState = RCC_PLL_NONE;\n`;
  s += `  if (HAL_RCC_OscConfig(&RCC_OscInitStruct) != HAL_OK)
  {
    Error_Handler();
  }

  /** Initializes the CPU, AHB and APB buses clocks
  */
  RCC_ClkInitStruct.ClockType = RCC_CLOCKTYPE_HCLK|RCC_CLOCKTYPE_SYSCLK
                              |RCC_CLOCKTYPE_PCLK1|RCC_CLOCKTYPE_PCLK2;
  RCC_ClkInitStruct.SYSCLKSource = ${k.sysclk === "PLL" ? "RCC_SYSCLKSOURCE_PLLCLK" : `RCC_SYSCLKSOURCE_${k.sysclk}`};
  RCC_ClkInitStruct.AHBCLKDivider = RCC_SYSCLK_DIV${k.ahbDiv};
  RCC_ClkInitStruct.APB1CLKDivider = RCC_HCLK_DIV${k.apb1Div};
  RCC_ClkInitStruct.APB2CLKDivider = RCC_HCLK_DIV${k.apb2Div};

  if (HAL_RCC_ClockConfig(&RCC_ClkInitStruct, FLASH_LATENCY_${t.latency}) != HAL_OK)
  {
    Error_Handler();
  }
}
`;
  return s;
}

const doc = (title: string) => `/**
  * @brief ${title}
  * @param None
  * @retval None
  */`;

const check = (call: string) => `  if (${call} != HAL_OK)
  {
    Error_Handler();
  }
`;

