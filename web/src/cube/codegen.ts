interface AfPin {
  pin: string;
  v: PinConfig;
  af: number;
  mode: "GPIO_MODE_AF_PP" | "GPIO_MODE_AF_OD" | "GPIO_MODE_ANALOG";
  pull: string;
  speed: string | null;
}

function afPins(c: CubeConfig, p: string): AfPin[] {
  const out: AfPin[] = [];
  for (const [pin, v] of pinsInOrder(c)) {
    if (p === "ADC1") {
      if (/^ADC1_IN/.test(v.signal)) out.push({ pin, v, af: -1, mode: "GPIO_MODE_ANALOG", pull: "GPIO_NOPULL", speed: null });
      continue;
    }
    if (!v.signal.startsWith(`${p}_`)) continue;
    const af = afNumber(pin, v.signal);
    if (af === null) continue;
    const i2c = /^I2C/.test(p);
    const tim = /^TIM/.test(p);
    out.push({ pin, v, af, mode: i2c ? "GPIO_MODE_AF_OD" : "GPIO_MODE_AF_PP", pull: PULL[v.pull ?? "none"], speed: SPEED[v.speed ?? (tim ? "low" : "very_high")] });
  }
  return out;
}

function gpioBlock(c: CubeConfig, p: string, indent: string): string {
  const pins = afPins(c, p);
  if (!pins.length) return "";
  const ports: string[] = [];
  for (const a of pins) if (!ports.includes(portPin(a.pin).port)) ports.push(portPin(a.pin).port);
  let s = ports.map((x) => `${indent}__HAL_RCC_GPIO${x}_CLK_ENABLE();\n`).join("");
  s += `${indent}/**${p} GPIO Configuration\n${pins.map((a) => `${indent}${a.pin.padEnd(8)}------> ${a.v.signal}\n`).join("")}${indent}*/\n`;
  const groups: AfPin[][] = [];
  for (const a of pins) {
    const g = groups.find((x) => portPin(x[0].pin).port === portPin(a.pin).port && x[0].af === a.af && x[0].mode === a.mode && x[0].pull === a.pull && x[0].speed === a.speed);
    if (g) g.push(a);
    else groups.push([a]);
  }
  for (const g of groups) {
    const list = g.map((a): [string, PinConfig] => [a.pin, a.v]);
    s += `${indent}GPIO_InitStruct.Pin = ${pinList(list)};
${indent}GPIO_InitStruct.Mode = ${g[0].mode};
${indent}GPIO_InitStruct.Pull = ${g[0].pull};
${g[0].speed ? `${indent}GPIO_InitStruct.Speed = ${g[0].speed};\n` : ""}${g[0].af >= 0 ? `${indent}GPIO_InitStruct.Alternate = ${afMacro(g[0].af, g[0].v.signal)};\n` : ""}${indent}HAL_GPIO_Init(${portExpr(list)}, &GPIO_InitStruct);

`;
  }
  return s;
}

function mspPair(c: CubeConfig, kind: string, handleType: string, arg: string, members: string[], body: (p: string) => { init: string; deinit: string }): string {
  if (!members.length) return "";
  const needsGpio = members.some((p) => afPins(c, p).length && kind !== "TIM_Base");
  const fn = (de: boolean) => {
    let s = `/**
* @brief ${kind.replace("_Base", " Base")} MSP ${de ? "De-Initialization" : "Initialization"}
* This function ${de ? "freeze" : "configures"} the hardware resources used in this example
* @param ${arg}: ${kind.replace("_Base", "_Base")} handle pointer
* @retval None
*/
void HAL_${kind}_Msp${de ? "DeInit" : "Init"}(${handleType}* ${arg})
{
${!de && needsGpio ? "  GPIO_InitTypeDef GPIO_InitStruct = {0};\n" : ""}`;
    members.forEach((p, i) => {
      const b = body(p);
      s += `  ${i ? "else if" : "if"}(${arg}->Instance==${p})
  {
  ${R(`${p}_Msp${de ? "DeInit" : "Init"} 0`, "\n\n  ")}
${de ? b.deinit : b.init}  ${R(`${p}_Msp${de ? "DeInit" : "Init"} 1`, "\n\n  ")}
  }
`;
    });
    return s + "\n}\n\n";
  };
  return fn(false) + fn(true);
}

function irqInit(c: CubeConfig, p: string, indent: string, label: string): string {
  const irqs = irqsOf(p).filter((i) => nvicOn(c, i));
  if (!irqs.length) return "";
  return `\n${indent}/* ${label} interrupt Init */\n` + irqs.map((i) => nvicLines(c, i, indent)).join("");
}

function irqDeinit(c: CubeConfig, p: string, indent: string, label: string): string {
  // A shared IRQ stays on while another enabled peripheral uses it.
  const irqs = irqsOf(p).filter((i) => nvicOn(c, i) && !peripherals(c).some((q) => q !== p && irqsOf(q).includes(i)));
  if (!irqs.length) return "";
  return `\n${indent}/* ${label} interrupt DeInit */\n` + irqs.map((i) => `${indent}HAL_NVIC_DisableIRQ(${i}_IRQn);\n`).join("");
}

function gpioDeinit(c: CubeConfig, p: string, indent: string): string {
  const pins = afPins(c, p);
  if (!pins.length) return "";
  const byPort = new Map<string, [string, PinConfig][]>();
  for (const a of pins) byPort.set(portPin(a.pin).port, [...(byPort.get(portPin(a.pin).port) ?? []), [a.pin, a.v]]);
  let s = `\n${indent}/**${p} GPIO Configuration\n${pins.map((a) => `${indent}${a.pin.padEnd(8)}------> ${a.v.signal}\n`).join("")}${indent}*/\n`;
  for (const [, list] of byPort) s += `${indent}HAL_GPIO_DeInit(${portExpr(list)}, ${pinList(list)});\n`;
  return s + "\n";
}

