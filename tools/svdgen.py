#!/usr/bin/env python3
"""Generate the STM32F401 register table from ST's CMSIS-SVD file.

    python3 tools/svdgen.py crates/periph-stm32f4/svd/STM32F401.svd \
        > crates/periph-stm32f4/src/svd.rs

The output is plain data (names, offsets, reset values, fields, interrupts)
used for reset values of peripherals without a behavioural model, readable
diagnostics ("RCC.PLLCFGR" instead of an address) and, later, the register
viewer in the GUI. Descriptions are left out to keep the WASM build small.
"""

import sys
import xml.etree.ElementTree as ET


def num(text, default=None):
    if text is None:
        return default
    t = text.strip().lower()
    if t.startswith("0x"):
        return int(t, 16)
    if t.startswith("#"):
        return int(t[1:].replace("x", "0"), 2)
    # Plain digits are decimal; leading zeros are allowed (e.g. "00000010").
    return int(t, 10)


def ident(name):
    return "".join(c if c.isalnum() else "_" for c in name).upper()


def main(path):
    root = ET.parse(path).getroot()
    dev_reset = num(root.findtext("resetValue"), 0)
    dev_access = root.findtext("access", "read-write")

    raw = {p.findtext("name"): p for p in root.find("peripherals").findall("peripheral")}

    def registers_of(p):
        src = p
        while src.find("registers") is None and src.get("derivedFrom"):
            src = raw[src.get("derivedFrom")]
        return src

    out = []
    w = out.append
    w("// @generated by tools/svdgen.py from svd/STM32F401.svd")
    w("// (Copyright STMicroelectronics, Apache-2.0). Do not edit by hand.")
    w("")
    w("use crate::svd_types::{Access, Field, Peripheral, Register};")
    w("")

    emitted = {}  # register-source peripheral name -> static ident
    peripherals = []
    for name, p in raw.items():
        src = registers_of(p)
        src_name = src.findtext("name")
        if src_name not in emitted:
            regs = []
            p_reset = num(src.findtext("resetValue"), dev_reset)
            p_access = src.findtext("access", dev_access)
            for r in src.find("registers").findall("register"):
                fields = []
                fs = r.find("fields")
                if fs is not None:
                    for f in fs.findall("field"):
                        if f.find("bitOffset") is not None:
                            lsb = num(f.findtext("bitOffset"))
                            width = num(f.findtext("bitWidth"))
                        else:
                            rng = f.findtext("bitRange").strip("[]").split(":")
                            msb, lsb = int(rng[0]), int(rng[1])
                            width = msb - lsb + 1
                        fields.append((f.findtext("name"), lsb, width))
                fields.sort(key=lambda x: x[1])
                access = r.findtext("access", p_access)
                regs.append(
                    (
                        r.findtext("name"),
                        num(r.findtext("addressOffset")),
                        num(r.findtext("resetValue"), p_reset),
                        access,
                        fields,
                    )
                )
            regs.sort(key=lambda x: x[1])
            static = f"REGS_{ident(src_name)}"
            emitted[src_name] = static
            w(f"static {static}: &[Register] = &[")
            for rname, off, reset, access, fields in regs:
                acc = {"read-only": "ReadOnly", "write-only": "WriteOnly"}.get(access, "ReadWrite")
                fl = ", ".join(f'Field {{ name: "{n}", lsb: {l}, width: {wd} }}' for n, l, wd in fields)
                w(
                    f'    Register {{ name: "{rname}", offset: 0x{off:03X}, reset: 0x{reset:08X}, '
                    f"access: Access::{acc}, fields: &[{fl}] }},"
                )
            w("];")
            w("")
        irqs = sorted({(i.findtext("name"), num(i.findtext("value"))) for i in p.findall("interrupt")}, key=lambda x: x[1])
        peripherals.append((name, num(p.findtext("baseAddress")), emitted[src_name], irqs))

    peripherals.sort(key=lambda x: x[1])
    w("/// All peripherals in the SVD, sorted by base address.")
    w("pub static PERIPHERALS: &[Peripheral] = &[")
    for name, base, regs, irqs in peripherals:
        il = ", ".join(f'("{n}", {v})' for n, v in irqs)
        w(f'    Peripheral {{ name: "{name}", base: 0x{base:08X}, registers: {regs}, interrupts: &[{il}] }},')
    w("];")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
